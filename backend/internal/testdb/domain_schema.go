func MigrateDomainSchema(db *gorm.DB) error {
	if err := db.AutoMigrate(DomainModels()...); err != nil {
		return err
	}
	for _, statement := range []string{
		"CREATE UNIQUE INDEX IF NOT EXISTS idx_resources_user_upload_key ON resources (user_id, upload_key)",
		"CREATE UNIQUE INDEX IF NOT EXISTS idx_project_asset_candidates_pending_identity ON project_asset_candidates(project_id, category, name_key) WHERE status = 'pending_confirmation' AND name_key <> ''",
		"CREATE UNIQUE INDEX IF NOT EXISTS idx_logical_model_active_code ON logical_models(code) WHERE archived_at IS NULL",
		"CREATE UNIQUE INDEX IF NOT EXISTS idx_logical_model_source_active ON logical_models(source_channel_model_id) WHERE source_channel_model_id <> '' AND archived_at IS NULL",
		"CREATE INDEX IF NOT EXISTS idx_cloud_agent_canvas_active ON cloud_agent_executions (user_id, id) WHERE status NOT IN ('completed', 'failed', 'cancelled', 'rejected') OR cleanup_pending = true",
		"CREATE INDEX IF NOT EXISTS idx_tasks_canvas_agent_reservation ON tasks (user_id, project_id, created_at, id) WHERE operation = 'cloud_agent' AND agent_execution_ready = false AND status NOT IN ('succeeded', 'failed', 'cancelled')",
	} {
		if err := db.Exec(statement).Error; err != nil {
			return err
		}
	}
	return nil
}
